import fs from 'node:fs';
import crypto from 'node:crypto';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
const conf=JSON.parse(fs.readFileSync('src-tauri/tauri.conf.json','utf8'));
const version=conf.version,folder='src-tauri/target/release/bundle/nsis';
const asset=`Ember_${version}_x64-setup.exe`,exe=fs.readFileSync(path.join(folder,asset));
const signature=fs.readFileSync(path.join(folder,asset+'.sig'),'utf8').trim();
const oldConf=JSON.parse(execFileSync('git',['show','v1.0.0:src-tauri/tauri.conf.json'],{encoding:'utf8'}));
if(conf.plugins.updater.pubkey!==oldConf.plugins.updater.pubkey)throw Error('Updater public key changed');
if(JSON.stringify(conf.plugins.updater.endpoints)!==JSON.stringify(oldConf.plugins.updater.endpoints))throw Error('Updater endpoint changed');
const previousConf=JSON.parse(execFileSync('git',['show','v1.1.0:src-tauri/tauri.conf.json'],{encoding:'utf8'}));
if(conf.plugins.updater.pubkey!==previousConf.plugins.updater.pubkey||JSON.stringify(conf.plugins.updater.endpoints)!==JSON.stringify(previousConf.plugins.updater.endpoints))throw Error('v1.1.0 updater compatibility changed');
const keyLines=Buffer.from(conf.plugins.updater.pubkey,'base64').toString().trim().split(/\r?\n/);
const pub=Buffer.from(keyLines[1],'base64');
const sigLines=Buffer.from(signature,'base64').toString().trim().split(/\r?\n/);
const sig=Buffer.from(sigLines[1],'base64');
if(!pub.subarray(2,10).equals(sig.subarray(2,10)))throw Error('Signature key id mismatch');
const publicKey=crypto.createPublicKey({key:Buffer.concat([Buffer.from('302a300506032b6570032100','hex'),pub.subarray(10)]),format:'der',type:'spki'});
const verify=data=>crypto.verify(null,sig.subarray(0,2).toString()==='ED'?crypto.createHash('blake2b512').update(data).digest():data,publicKey,sig.subarray(10));
if(!verify(exe))throw Error('Installer signature verification failed');
const damaged=Buffer.from(exe);damaged[Math.floor(damaged.length/2)]^=1;
if(verify(damaged))throw Error('Tampered payload unexpectedly verified');
const comment=sigLines[2].replace(/^trusted comment: /,'');
if(!crypto.verify(null,Buffer.concat([sig.subarray(10),Buffer.from(comment)]),publicKey,Buffer.from(sigLines[3],'base64')))throw Error('Trusted comment signature failed');
const manifest={version,notes:fs.readFileSync(`docs/RELEASE_${version}.md`,'utf8'),pub_date:new Date().toISOString(),platforms:{'windows-x86_64':{signature,url:`https://github.com/sanirudh17/Ember/releases/download/v${version}/${asset}`}}};
fs.writeFileSync(path.join(folder,'latest.json'),JSON.stringify(manifest,null,2)+'\n');
const assets=[asset,asset+'.sig','latest.json'];
fs.writeFileSync(path.join(folder,'SHA256SUMS.txt'),assets.map(name=>crypto.createHash('sha256').update(fs.readFileSync(path.join(folder,name))).digest('hex')+'  '+name).join('\n')+'\n');
console.log('PASS: installer signature with v1.0.0 key, trusted comment, tamper rejection, unchanged updater endpoint, BOM-free manifest and SHA-256 checksums');
